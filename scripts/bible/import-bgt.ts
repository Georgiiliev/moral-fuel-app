/**
 * npm run bible:import [-- --fetch]
 *
 * Builds src/content/bible/bgt.json from the publisher's chapter pages: pages the owner saved in a
 * browser (bible-sources/bgt/*.html) and, with --fetch, pages fetched where the site permits it.
 * Only the chapters and verses the lessons use are kept. Then verifies and writes the reports.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { blocksInRange, uncoveredVerses, verseSpan } from '@/content/bible';
import type { BibleChapterText, BibleDataset } from '@/models/bible';
import { BIBLE_BOOKS } from '@/models/content';

import { buildManifest, PROJECT_ROOT, type Manifest, type ManifestChapter } from './manifest';
import { chapterKey, DATASET_PATH, FETCHED_DIR, IMPORT_VERSION, readSourcePages, type SourcePage } from './sources';
import { verifyDataset, writeVerificationReport } from './validate';

const REPORT_PATH = join(PROJECT_ROOT, 'BGT_IMPORT_REPORT.md');
const USER_AGENT = 'MoralFuel-BGT-import/1.0 (content import authorised by the app owner)';
const FETCH_PAUSE_MS = 2000;

/** Null when robots.txt can be read and leaves /bijbel/BGT/ open; otherwise why fetching is off. */
async function fetchRefusal(): Promise<string | null> {
  const response = await fetch('https://www.debijbel.nl/robots.txt', { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) return `robots.txt answered HTTP ${response.status}`;
  let appliesToAll = false;
  for (const line of (await response.text()).split('\n')) {
    const [field, ...rest] = line.split(':');
    const value = rest.join(':').trim();
    if (/^user-agent$/i.test(field.trim())) appliesToAll = value === '*';
    if (appliesToAll && /^disallow$/i.test(field.trim()) && value && '/bijbel/BGT/'.startsWith(value)) {
      return `robots.txt disallows ${value}`;
    }
  }
  return null;
}

/** Fetches missing chapters one at a time and stops at the first refusal or rate limit. */
async function fetchMissing(chapters: ManifestChapter[], have: Map<string, SourcePage>): Promise<string[]> {
  const refusal = await fetchRefusal();
  if (refusal) return [`Fetching skipped: ${refusal}.`];
  mkdirSync(FETCHED_DIR, { recursive: true });
  for (const chapter of chapters.filter((item) => !have.has(chapterKey(item)))) {
    const response = await fetch(chapter.url, { headers: { 'User-Agent': USER_AGENT } });
    if (!response.ok) return [`Fetching stopped at ${chapter.url}: HTTP ${response.status}.`];
    writeFileSync(join(FETCHED_DIR, `${chapterKey(chapter)}.html`), await response.text());
    await new Promise((resolve) => setTimeout(resolve, FETCH_PAUSE_MS));
  }
  return [];
}

/** The part of each needed chapter the lessons use, in canonical order. */
export function buildChapters(manifest: Manifest, pages: Map<string, SourcePage>): BibleChapterText[] {
  return manifest.chapters
    .flatMap((needed) => {
      const source = pages.get(chapterKey(needed));
      if (!source) return [];
      const { page } = source;
      const blocks = blocksInRange(page.blocks, needed.first, needed.last ?? page.verseCount);
      const notes = manifest.references
        .filter((ref) => ref.bookId === needed.book && ref.chapter === needed.chapter)
        .flatMap((ref) => {
          const reference = { book: ref.bookId, chapter: ref.chapter, verseStart: ref.verseStart ?? undefined, verseEnd: ref.verseEnd ?? undefined };
          const { first, last } = verseSpan(reference, page.verseCount);
          const missing = uncoveredVerses(blocksInRange(blocks, first, last), first, last);
          return missing.length > 0 ? [`${ref.label}: verses ${missing.join(', ')} not found in the source`] : [];
        });
      const chapter: BibleChapterText = {
        translation: 'BGT',
        book: needed.book,
        chapter: needed.chapter,
        verseCount: page.verseCount,
        blocks,
        source: { url: needed.url, retrievedOn: source.savedOn, via: source.via, sha256: source.sha256, importVersion: IMPORT_VERSION },
        status: notes.length > 0 ? 'NEEDS_REVIEW' : 'IMPORTED',
        ...(notes.length > 0 ? { notes } : {}),
      };
      return [chapter];
    })
    .sort((a, b) => BIBLE_BOOKS.indexOf(a.book) - BIBLE_BOOKS.indexOf(b.book) || a.chapter - b.chapter);
}

function writeImportReport(manifest: Manifest, dataset: BibleDataset, pages: Map<string, SourcePage>, problems: string[]) {
  const imported = new Set(dataset.chapters.map(chapterKey));
  const missing = manifest.chapters.filter((chapter) => !imported.has(chapterKey(chapter)));
  const lines = [
    '# BGT import report',
    '',
    `Generated by \`npm run bible:import\` on ${new Date().toISOString().slice(0, 10)}. Import version ${IMPORT_VERSION}.`,
    '',
    `- Chapters needed by the lessons: ${manifest.chapters.length}`,
    `- Chapter pages found in \`bible-sources/bgt\`: ${pages.size}`,
    `- Chapters imported: ${dataset.chapters.length}`,
    `- Chapters still missing: ${missing.length}`,
    '',
    '## Imported',
    '',
    ...(dataset.chapters.length > 0
      ? ['| Chapter | Status | Source file | Saved | Verses kept |', '| --- | --- | --- | --- | --- |']
      : ['None yet.']),
    ...dataset.chapters.map((chapter) => {
      const verses = chapter.blocks.flatMap((block) => (block.kind === 'paragraph' ? block.verses : []));
      const span = verses.length > 0 ? `${verses[0].first}-${verses[verses.length - 1].last} of ${chapter.verseCount}` : '-';
      return `| ${chapterKey(chapter)} | ${chapter.status} | ${pages.get(chapterKey(chapter))?.file ?? '-'} | ${chapter.source.retrievedOn} | ${span} |`;
    }),
    '',
    '## Missing (save these pages to import them)',
    '',
    ...(missing.length > 0 ? missing.map((chapter) => `- ${chapterKey(chapter)}: ${chapter.url}`) : ['None.']),
    '',
    '## Problems',
    '',
    ...(problems.length > 0 ? problems.map((problem) => `- ${problem}`) : ['None.']),
    '',
  ];
  writeFileSync(REPORT_PATH, lines.join('\n'));
}

/** Runs another bible script in a fresh process, so it reads the dataset just written. */
function runScript(name: string) {
  const result = spawnSync(process.execPath, [...process.execArgv, join(__dirname, name)], { stdio: 'inherit' });
  if (result.status !== 0) process.exitCode = result.status ?? 1;
}

async function main() {
  const manifest = buildManifest();
  const fetching = process.argv.includes('--fetch');
  const fetchProblems = fetching ? await fetchMissing(manifest.chapters, readSourcePages().pages) : [];
  const sources = readSourcePages();
  const problems = [...fetchProblems, ...sources.problems];

  const verification = verifyDataset(
    { translation: 'BGT', importVersion: IMPORT_VERSION, chapters: buildChapters(manifest, sources.pages) },
    sources.pages,
  );
  const dataset: BibleDataset = { translation: 'BGT', importVersion: IMPORT_VERSION, chapters: verification.chapters };
  writeFileSync(DATASET_PATH, `${JSON.stringify(dataset, null, 2)}\n`);
  writeImportReport(manifest, dataset, sources.pages, problems);
  writeVerificationReport(verification);
  console.log(
    `${dataset.chapters.length}/${manifest.chapters.length} chapters imported, ${verification.problems.length} verification problems, ${problems.length} import problems (BGT_IMPORT_REPORT.md).`,
  );
  runScript('manifest.ts');
  runScript('coverage.ts');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
